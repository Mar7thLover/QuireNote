/** 当前界面语言的文字。 */
export function msg(): ServerMessages {
  return currentLang() === "en" ? en : zh;
}

/** 生成物类型名（core 里带中英两种）。 */
export function kindLabel(kind: ArtifactKind): string {
  const meta = ARTIFACT_KIND_META[kind];
  return currentLang() === "en" ? meta.labelEn : meta.label;
}

/** 提供方类型名（目录里带中英两种）。 */
export function providerLabel(kind: ProviderKind): string {
  const entry = catalogEntry(kind);
  return currentLang() === "en" ? entry.labelEn : entry.label;
}

/** 新对话的默认标题（两种语言都算默认，自动改名时用）。 */
export function isDefaultConversationTitle(title: string): boolean {
  return title === zh.defaultConversationTitle || title === en.defaultConversationTitle;
}
